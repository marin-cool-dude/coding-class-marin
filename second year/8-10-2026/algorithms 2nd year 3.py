integer = int(input("Input an integer: "))
if (integer == 100):
    print("Your integer is equal to 100.")
if (integer > 100):
    print("Your integer is greater than 100.")
if (integer < 100):
    print("Your integer is less than 100.")
if(integer >= 100):
    print("Your integer is greater than or equal to 100.")
if (integer <= 100):
    print("Your integer is less than or equal to 100.")
if (integer != 100):
    print("Your integer is not equal to 100.")